import fs from 'node:fs'
import path from 'node:path'
import ts from 'typescript'
import { Converter } from 'opencc-js'

const webRoot = path.resolve(import.meta.dirname, '..')
const sourceRoot = path.join(webRoot, 'src')
const outputPath = path.join(sourceRoot, 'i18n', 'generated-hant.ts')
const hasHan = /[\u3400-\u9fff\uf900-\ufaff]/u
const convert = Converter({ from: 'cn', to: 'twp' })

const taiwanUiTerms = [
  ['賬戶', '帳戶'],
  ['賬本', '帳本'],
  ['賬單', '帳單'],
  ['對賬', '對帳'],
  ['郵箱', '電子郵件'],
  ['繫結', '綁定'],
  ['憑據', '憑證'],
  ['許可權', '權限'],
  ['平臺', '平台'],
  ['質量', '品質'],
  ['屏幕', '螢幕'],
  ['全域性', '全站'],
  ['程式碼', '代碼'],
  ['模擬盤', '模擬交易'],
  ['買入', '買進'],
  ['止損', '停損'],
  ['風控', '風險控管'],
  ['收益率', '報酬率'],
  ['收益', '報酬'],
  ['盈虧', '損益'],
  ['佣金', '傭金'],
  ['倉位', '持倉'],
  ['實時', '即時'],
  ['釋出', '發布'],
  ['稽覈', '審核'],
]

const requiredUiPhrases = [
  '账户', '会员订单', '模拟交易', '模拟订单', '买入', '卖出', '止损', '最大亏损',
  '未实现盈亏', '已实现盈亏', '收益率', '风险控制', '风控', '仓位', '持仓',
  '自选', '自选股', '美股', 'A股', '行情', '下单', '蜡烛图', '与成交量',
  '界面演示行情', '包含', '个模拟成交标记',
  '登录', '退出登录', '简体中文', '繁体中文',
  '已付款', '已批准', '已回退', '部分回退', '佣金回退', '已人工付款', '正在提交…',
  '佣金', '冻结佣金',
]

const requiredUiTranslations = new Map([
  ['已付款', '已撥款'],
  ['已批准', '已核准'],
  ['已回退', '已追回'],
  ['部分回退', '部分追回'],
  ['佣金回退', '傭金追回'],
  ['已人工付款', '已人工撥款'],
  ['正在提交…', '正在送出…'],
  ['冻结佣金', '凍結傭金'],
])

function toTaiwanUi(value) {
  let translated = convert(value)
  for (const [source, target] of taiwanUiTerms) translated = translated.replaceAll(source, target)
  return translated
}

function filesBelow(root, extensions) {
  if (!fs.existsSync(root)) return []
  const files = []
  for (const entry of fs.readdirSync(root, { withFileTypes: true })) {
    if (entry.name === 'node_modules' || entry.name === 'dist' || entry.name.startsWith('.')) continue
    const target = path.join(root, entry.name)
    if (entry.isDirectory()) files.push(...filesBelow(target, extensions))
    else if (extensions.has(path.extname(entry.name))) files.push(target)
  }
  return files
}

const uiFiles = filesBelow(sourceRoot, new Set(['.ts', '.tsx']))
  .filter((file) => file !== outputPath)
const phrases = new Set()
for (const phrase of requiredUiPhrases) phrases.add(phrase)

for (const file of uiFiles) {
  const content = fs.readFileSync(file, 'utf8')
  const source = ts.createSourceFile(file, content, ts.ScriptTarget.Latest, true)
  const visit = (node) => {
    if (
      ts.isStringLiteralLike(node)
      || ts.isNoSubstitutionTemplateLiteral(node)
      || ts.isTemplateHead(node)
      || ts.isTemplateMiddle(node)
      || ts.isTemplateTail(node)
      || ts.isJsxText(node)
    ) {
      const value = ts.isJsxText(node) ? node.text.replace(/\s+/g, ' ').trim() : node.text
      if (value && hasHan.test(value)) phrases.add(value)
    }
    ts.forEachChild(node, visit)
  }
  visit(source)
}

const phrasePairs = [...phrases]
  .map((value) => [value, requiredUiTranslations.get(value) ?? toTaiwanUi(value)])
  .filter(([source, translated]) => source !== translated || requiredUiTranslations.has(source))
  .sort((left, right) => right[0].length - left[0].length || left[0].localeCompare(right[0]))

const generated = `// Generated by scripts/build-locale-catalog.mjs. Do not edit manually.\n\nexport const HANT_PHRASES = ${JSON.stringify(phrasePairs, null, 2)} as const\n`
fs.writeFileSync(outputPath, generated, 'utf8')
console.log(`Generated ${phrasePairs.length} approved UI phrase mappings.`)
